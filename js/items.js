// Washable Dinan filter: the item becomes "clean", not "replace".
export function applyAirFilterType(def, type) {
  if (def.id !== 'airfilter') return def;
  if (type === 'washable') {
    return {
      ...def,
      name: 'Air filter (clean, reusable)',
      short: 'Your Dinan filter is washable, so it gets cleaned and reused instead of replaced.',
      tag: 'Washable filter',
      why: 'Washable filters are cleaned, not thrown away. This starts at BMW\'s factory interval as a placeholder. Check your Dinan paperwork for their cleaning interval and edit it here.',
      source: 'Placeholder: BMW factory interval. Confirm with Dinan.',
      diyNote: 'Use the cleaning method Dinan recommends for your filter.',
      defaultQuote: null,
    };
  }
  return def;
}
